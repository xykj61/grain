#!/bin/sh
# tools/fixtures/f/falsifier_verdict_home_scan.sh -- does a graded row carry its verdict?
#
# A paper of this lane runs an elder paper's falsifier and reaches a verdict.
# The verdict is worth something to exactly one reader: the person who opens the
# ELDER page and reads the row that has since been refuted. So the question this
# scan asks is a question about POSITION rather than about wording -- when a
# child declares `row N of <elder>`, does the elder carry a `Row N erratum` line?
#
# Output convention: context/specs/20260729-215600_scan-seam-convention.md
#
# WHY A POSITION AND NEVER A SPELLING, which is the whole reason this instrument
# exists and the reason it gates what it gates. On `20260909.203002`
# external-research/date/20260909/20260909-203002_the-declaration-grew-in-the-door.md withdrew
# its own proposed construction/falsifier-ledger.kyri and seated one door key in
# its place -- `**Runs the falsifier of:** <elder> -- survived | fired |
# unrunnable` -- with a one-command kill condition: read the next twenty papers,
# and if fewer than half of those running an elder's falsifier use the seated
# spelling, withdraw it. Eight days and 127 pages later the key stands in three
# files, every one of them written before or within the hour of its own seating,
# and the seven papers that ran an elder falsifier since declared the relation
# under SIX other keys -- Answers, Serves, Reads, Grades, Subject, Elder. The
# falsifier fired.
#
# What grew in the same eight days, unprompted, is COMPLETE: all twelve ranked
# rows of active-designing/date/20260910/20260910-060204_the-bounded-torus-moonshots.md carry a
# `Row N erratum:` line stamped by the child paper that graded them. A spelling
# must be remembered and a position is found by looking, which is why one
# converged and the other never did.
#
# THE PAGES READ. Living tracked .md under external-research/ and active-designing/.
# The archive/ and yonder/ shelves are read past: .claude/rules/read-scope.md names
# them closed stacks, and accrete-never-break keeps every word a shelved page wrote,
# so an unanswered declaration there is testimony rather than a debt. A page folded
# to its own date/ shelf stays IN the reading -- a graded elder's own errata accrue
# over days, so it is expected to fold there while still gradeable, the same lesson
# tools/fixtures/f/falsifier_form_outcome_scan.sh already learned (REDS 20260925.232420)
# when both elder pages this scan's own header names above turned out to be exactly
# that shape: dated-basename, `Status: Proposed`, folded to date/ and still open to
# a new declaration naming a row of them.
#
# THE READINGS:
#   declarations  -- a line naming an elder basename and a row number, under any
#                    key, in either order. Form A carries its own pairing --
#                    `row N of [`basename`]`; form B has the link and the row on
#                    one line and is paired first-with-first.
#   answered      -- the elder page carries a matching `**Row <N> erratum:**`
#   unanswered    -- it does not. GATED AT ZERO: the child already did the work,
#                    and the reader who needs it is standing on the elder page.
#   elder_missing -- the basename resolves to no living tracked page. REPORTED:
#                    an elder that folded to a shelf is lawful, and the resolver
#                    at tools/d/dated_path_resolve.rish is how a reference to one
#                    is recovered rather than rewritten.
#   elders_distinct -- how many elder pages the declarations name. One today, so
#                    the census describes one page's habit and says so out loud.
#   erratum_no_paper -- an erratum whose stamp names no page in the two rooms.
#                    REPORTED and never gated: a lap may run a witness and record
#                    the result without writing a paper, and two such stand today.
#   key_seated    -- files carrying the withdrawn spelling. REPORTED. Gating a
#                    spelling this instrument's own paper refuted would be a meter
#                    arguing with its own reading.
#
#   rowless_gradings -- a door line declaring an elder under a key that names the
#                    ACT of running or grading, carrying NO row number: a page
#                    that graded an elder's whole sentence rather than one row.
#                    See THE ROWLESS HALF below for why this is a typed roster.
#   rowless_answered -- the elder carries a line naming the CHILD'S STAMP, in
#                    either of the two shapes this collection actually grew:
#                    a rowless `**Erratum:** <stamp>` field, or an anchored
#                    `## Addendum <stamp>` section.
#   rowless_unanswered -- it does not. REPORTED, never gated; see below.
#   rowless_outside_roster -- rowless door lines naming an elder under a key the
#                    roster does not hold. This reading PRICES THE ROSTER'S OWN
#                    BLINDNESS and is the reason the roster can be typed honestly.
#
# THE ROWLESS HALF, and why it reports where the row half gates. The elder
# spelling of this header said a rowless grading was invisible here and priced
# the class from one hand-run regular expression: `finds two of six`. Measured
# `20260917.135913` over the same 498 living pages, the population is larger and
# its shape is the finding. **156 rowless door lines name an elder basename**, so
# reading them all would grow the gated set 15 to 171 -- and **150 of them sit
# outside any key naming the act of grading, 133 of those under just five**: Kin,
# Ground, Companions, Elder and Status, keys that POINT a reader at a neighbour
# rather than grade it. A gate over that set would demand an erratum for every
# `Kin` pointer in the two rooms. The 150 is `rowless_outside_roster`, printed on
# every run; the 133 is five of its 22 named keys, and the two figures were
# conflated in this header's first draft, which is why both are spelled apart now.
#
# THE KEY CANNOT SEPARATE THEM BY ITSELF: `Kin` and `Elder` appear among the
# row-naming declarations too, so no key is a grading key per se. Verdict
# vocabulary cannot either -- two `Kin` lines carry `fired` while merely
# describing a THIRD party's verdict. What remains is the narrow reading: a key
# that names the act. Under `Runs the falsifier of`, `Grades` and `Answers` the
# rowless population is **six**, and each was checked by hand.
#
# WHAT THE FIVE SHOWED, which is why this half exists at all. Two elders answer
# in shapes this scan never read -- `**Erratum:** 20260917.132232` on one, and
# `## Addendum 20260908.005732 -- the third falsifier was run` on another, the
# latter carrying a full three-row verdict table. **A SECOND STRUCTURAL SHAPE
# CONVERGED UNPROMPTED, exactly as the row erratum did**, and for the same reason
# the withdrawn door key never did: both are found by looking rather than
# remembered. The remaining **three elders carry no line naming the child's stamp
# at all** -- verdicts reached and never carried home to the reader standing on
# the elder page.
#
# SO IT REPORTS AND NEVER GATES, and the reason is this instrument's own paper.
# That paper refuted a seated SPELLING by measuring its adoption, and the
# declaration side here rests on a typed three-key roster -- a spelling, which
# must be remembered. Gating a reading whose population is drawn by a roster
# would red the lap a lane reaches for a sixth key nobody typed. The kill
# condition is one command: read the next twenty pages that grade an elder
# without a row, and if the roster names fewer than half of them, the roster is
# the wrong instrument and `rowless_outside_roster` is where the evidence sits.
#
# WHAT IT STILL CANNOT READ. A grading in PROSE ALONE, under no door key at all,
# is invisible to both halves. So `declarations` and `rowless_gradings` are each a
# floor on their real population, never the population, and the row half is honest
# exactly to the extent that a hand wrote the row number down.
set -eu

[ -d .git ] || { echo "verdict=not_a_repo"; exit 2; }

list=false
[ "${1:-}" = "--list" ] && list=true

# Bound everything (TAME): a collection past this many declarations is one this
# reading was never sized for, and it refuses rather than truncating in silence.
MAX_DECL=4096

pages=$(mktemp 2>/dev/null || echo "./.vh_pages.$$")
decl=$(mktemp 2>/dev/null || echo "./.vh_decl.$$")
errata=$(mktemp 2>/dev/null || echo "./.vh_errata.$$")
trap 'rm -f "$pages" "$decl" "$errata"' EXIT INT TERM

git ls-files 'external-research/*.md' 'active-designing/*.md' 2>/dev/null \
  | grep -vE '/(archive|yonder)/' > "$pages" || true

living=$(wc -l < "$pages" | tr -d ' ')
[ "$living" -gt 0 ] || { echo "verdict=no_pages_found"; exit 2; }

# ONE AWK for the declarations. A door line carries the relation as
# `**<Key>:** row <N> of [`<basename>`](...)`; the key is captured rather than
# constrained, because the census of keys is the reading that fired the spelling.
< "$pages" xargs awk '
  {
    line = $0
    if (line !~ /\[`[0-9]{8}-[0-9]{6}/) next
    if (line !~ /row [0-9]+/) next
    key = "-"
    if (match(line, /^\*\*[A-Za-z ]+:\*\*/)) key = substr(line, RSTART + 2, RLENGTH - 5)

    # FORM A -- `row N of [`basename`]`, the shape that carries its own pairing.
    hits = 0
    rest = line
    while (match(rest, /row [0-9]+ of \[`[0-9]{8}-[0-9]{6}[^`]*`\]/)) {
      hit = substr(rest, RSTART, RLENGTH)
      rest = substr(rest, RSTART + RLENGTH)
      n = hit; sub(/^row /, "", n); sub(/ .*/, "", n)
      b = hit; sub(/^.*\[`/, "", b); sub(/`\].*$/, "", b)
      printf "decl\tA\t%s\t%s\t%s\t%s\n", FILENAME, key, n, b
      hits++
    }
    if (hits > 0) next

    # FORM B -- the link and the row number on one line in either order, which is
    # how three declarations in this collection are actually written. It is confined
    # to a DOOR line -- a `**Key:**` field inside the first 25 lines of the page --
    # because outside the door that shape is ordinary prose about a table, and an
    # unconfined form B read 15 such lines and named 13 elders that were never
    # graded. The door bound of 25 comes from the withdrawal paper, which counted
    # adoption in `a header field within the first twenty-five lines`.
    # First is paired with first, so a door line naming two rows of two elders
    # reads as one and the census undercounts rather than guessing.
    if (key == "-" || FNR > 25) next
    match(line, /\[`[0-9]{8}-[0-9]{6}[^`]*`\]/)
    b = substr(line, RSTART + 2, RLENGTH - 4)
    match(line, /row [0-9]+/)
    n = substr(line, RSTART + 4, RLENGTH - 4)
    printf "decl\tB\t%s\t%s\t%s\t%s\n", FILENAME, key, n, b
  }
' > "$decl" || true

declarations=$(awk 'END{print NR+0}' "$decl")
[ "$declarations" -le "$MAX_DECL" ] || { echo "verdict=over_bound"; echo "detail: $declarations declarations past MAX_DECL=$MAX_DECL"; exit 2; }

# ONE AWK for the errata, keyed by page and row, so the answer side is read once
# rather than once per declaration.
# `anchored` is a variable rather than a `^` inside the pattern so the pen can
# lift the anchor in one substitution: an elder MENTIONING an erratum mid-sentence
# must never read as carrying one, and a mutation is how that is proven.
< "$pages" xargs awk -v anchored=1 '
  {
    if (!match($0, /\*\*Row [0-9]+ erratum:\*\*/)) next
    if (anchored && RSTART != 1) next
    n = $0; sub(/^.*\*\*Row /, "", n); sub(/ .*/, "", n)
    s = "-"
    if (match($0, /`[0-9]{8}\.[0-9]{6}`/)) s = substr($0, RSTART + 1, RLENGTH - 2)
    printf "err\t%s\t%s\t%s\n", FILENAME, n, s
  }
' > "$errata" || true

errata_total=$(awk 'END{print NR+0}' "$errata")

form_b=$(awk -F'\t' '$2=="B"{n++} END{print n+0}' "$decl")
answered=0
unanswered=0
elder_missing=0

while IFS="$(printf '\t')" read -r _t form child key n base; do
  [ -n "${base:-}" ] || continue
  elder=$(grep -E "/${base}\$" "$pages" | head -1 || true)
  if [ -z "$elder" ]; then
    elder_missing=$((elder_missing + 1))
    $list && echo "detail: elder_missing $child form=$form key=$key row=$n elder=$base"
    continue
  fi
  if awk -F'\t' -v p="$elder" -v n="$n" '$2==p && $3==n {found=1} END{exit found?0:1}' "$errata"; then
    answered=$((answered + 1))
    $list && echo "detail: answered $child form=$form key=$key row=$n elder=$base"
  else
    unanswered=$((unanswered + 1))
    $list && echo "detail: unanswered $child form=$form key=$key row=$n elder=$base"
  fi
done < "$decl"

# An erratum's stamp names the lap that graded the row. Where no page in these
# two rooms carries that stamp, the evidence lives in a session log instead --
# lawful, and worth seeing.
erratum_no_paper=0
while IFS="$(printf '\t')" read -r _t page n stamp; do
  [ "${stamp:-}" = "-" ] && continue
  hyph=$(printf '%s' "$stamp" | tr '.' '-')
  if ! grep -q "/${hyph}_" "$pages"; then
    erratum_no_paper=$((erratum_no_paper + 1))
    $list && echo "detail: erratum_no_paper $page row=$n stamp=$stamp"
  fi
done < "$errata"

elders_distinct=$(awk -F'\t' '$1=="decl"{print $6}' "$decl" | sort -u | awk 'END{print NR+0}')
keys_distinct=$(awk -F'\t' '$1=="decl"{print $4}' "$decl" | sort -u | tr '\n' ',' | sed 's/,$//')
keys_count=$(awk -F'\t' '$1=="decl"{print $4}' "$decl" | sort -u | wc -l | tr -d ' ')
key_seated=$(< "$pages" xargs grep -l 'Runs the falsifier of:' 2>/dev/null | wc -l | tr -d ' ')

# ------------------------------------------------------------------ the rowless half
# A rowless grading is paired by the CHILD'S OWN STAMP rather than by a row
# number, because a whole-page verdict has no row to be found at. Every page
# carries a stamp in its basename, so the pairing needs nothing a hand must
# remember -- which is the same property that made the row erratum converge.
#
# ROWLESS_KEYS is the roster, typed, and named here rather than inlined so the
# one thing a reader must audit sits on one line. `rowless_outside_roster` counts
# what it leaves behind, so the roster can never quietly become the population.
ROWLESS_KEYS='Runs the falsifier of|Grades|Answers'

rdecl=$(mktemp 2>/dev/null || echo "./.vh_rdecl.$$")
radd=$(mktemp 2>/dev/null || echo "./.vh_radd.$$")
trap 'rm -f "$pages" "$decl" "$errata" "$rdecl" "$radd"' EXIT INT TERM

# Pass one -- the rowless declarations, and the roster's own cost beside them.
# Confined to the door for the same reason form B is: outside it, a body line
# linking a dated page under a bolded lead is ordinary prose about a neighbour.
< "$pages" xargs awk -v keys="$ROWLESS_KEYS" '
  FNR > 25 { next }
  {
    line = $0
    if (line !~ /^\*\*[A-Za-z ]+:\*\*/) next
    if (line !~ /\[`[0-9]{8}-[0-9]{6}/) next
    # A row number on the line makes this the OTHER half is subject; never both.
    if (line ~ /row [0-9]+/) next
    match(line, /^\*\*[A-Za-z ]+:\*\*/)
    key = substr(line, RSTART + 2, RLENGTH - 5)
    match(line, /\[`[0-9]{8}-[0-9]{6}[^`]*`\]/)
    b = substr(line, RSTART + 2, RLENGTH - 4)
    # The roster is matched as a WHOLE key, so `Answers` never admits `Answered
    # by` and a longer key sharing a prefix stays outside until it is typed.
    inroster = 0
    n = split(keys, k, "|")
    for (i = 1; i <= n; i++) if (key == k[i]) inroster = 1
    printf "%s\t%s\t%s\t%s\n", (inroster ? "rdecl" : "rout"), FILENAME, key, b
  }
' > "$rdecl" || true

rowless_gradings=$(awk -F'\t' '$1=="rdecl"{n++} END{print n+0}' "$rdecl")
rowless_outside=$(awk -F'\t' '$1=="rout"{n++} END{print n+0}' "$rdecl")
[ "$rowless_gradings" -le "$MAX_DECL" ] || { echo "verdict=over_bound"; echo "detail: $rowless_gradings rowless gradings past MAX_DECL=$MAX_DECL"; exit 2; }

# Pass two -- the answer side, in the two shapes this collection grew. Both are
# ANCHORED at column 1 for the reason the row erratum is: a page discussing an
# addendum mid-sentence must never read as carrying one. The stamp is the key.
< "$pages" xargs awk '
  {
    if (match($0, /^\*\*Erratum:\*\*/)) shape = "erratum"
    else if (match($0, /^## Addendum/)) shape = "addendum"
    else next
    if (!match($0, /`[0-9]{8}\.[0-9]{6}`/)) next
    printf "radd\t%s\t%s\t%s\n", FILENAME, substr($0, RSTART + 1, RLENGTH - 2), shape
  }
' > "$radd" || true

rowless_answered=0
rowless_unanswered=0
rowless_elder_missing=0
while IFS="$(printf '\t')" read -r _t child key base; do
  # The roster rows only. `rout` rows share this file so the roster's cost is
  # counted from one pass, and reading them here would put every `Kin` pointer
  # in front of a reading that is about gradings.
  [ "${_t:-}" = "rdecl" ] || continue
  [ -n "${base:-}" ] || continue
  elder=$(grep -E "/${base}\$" "$pages" | head -1 || true)
  # The child's own stamp, read off its basename: YYYYMMDD-HHMMSS -> YYYYMMDD.HHMMSS.
  st=$(basename "$child" | cut -c1-15 | tr '-' '.')
  if [ -z "$elder" ]; then
    rowless_elder_missing=$((rowless_elder_missing + 1))
    $list && echo "detail: rowless_elder_missing $child key=$key elder=$base"
    continue
  fi
  if awk -F'\t' -v p="$elder" -v s="$st" '$2==p && $3==s {f=1} END{exit f?0:1}' "$radd"; then
    shape=$(awk -F'\t' -v p="$elder" -v s="$st" '$2==p && $3==s {print $4; exit}' "$radd")
    rowless_answered=$((rowless_answered + 1))
    $list && echo "detail: rowless_answered $child key=$key shape=$shape elder=$base"
  else
    rowless_unanswered=$((rowless_unanswered + 1))
    $list && echo "detail: rowless_unanswered $child key=$key stamp=$st elder=$base"
  fi
done < "$rdecl"

rowless_keys=$(awk -F'\t' '$1=="rout"{print $3}' "$rdecl" | sort -u | tr '\n' ',' | sed 's/,$//')
rowless_shapes=$(awk -F'\t' '{print $4}' "$radd" | sort -u | tr '\n' ',' | sed 's/,$//')

verdict=answered
[ "$unanswered" -gt 0 ] && verdict=unanswered

echo "living_pages=$living"
echo "declarations=$declarations"
echo "declarations_form_b=$form_b"
echo "answered=$answered"
echo "unanswered=$unanswered"
echo "elder_missing=$elder_missing"
echo "errata_total=$errata_total"
echo "erratum_no_paper=$erratum_no_paper"
echo "elders_distinct=$elders_distinct"
echo "keys_count=$keys_count"
echo "keys=$keys_distinct"
echo "key_seated=$key_seated"
echo "rowless_gradings=$rowless_gradings"
echo "rowless_answered=$rowless_answered"
echo "rowless_unanswered=$rowless_unanswered"
echo "rowless_elder_missing=$rowless_elder_missing"
echo "rowless_outside_roster=$rowless_outside"
echo "rowless_outside_keys=$rowless_keys"
echo "rowless_answer_shapes=$rowless_shapes"
echo "verdict=$verdict"
