#!/bin/sh
# caravan_ladder_carry_scan.sh -- how much of the Caravan ladder is a body the
# ladder has already written somewhere else, asked of EVERY body rather than of
# one named family.
#
# Three meters already stand beside this one, and each reads through a named
# window. `caravan_ladder_copy_scan.sh` reads bodies whose name opens on
# `check_`. `caravan_ladder_print_scan.sh` reads bodies whose name opens on
# `tell_`. `caravan_ladder_spine_scan.sh` reads one named function,
# `close_the_quarrel`. Every one of the three is honest inside its window and
# says so at the top, and together they governed eleven folds.
#
# What none of them can see is a body named anything else. That blindness was
# measured on `20260821` rather than reasoned about: `stand_taking_and_returning_reach`
# stood BYTE FOR BYTE in forty-two rungs at forty-four lines apiece -- the
# largest single carry the arc had ever folded -- and it rode past all three
# meters for six consecutive folds, because it opens on `stand_`. The fold that
# lifted it was found by hand, by asking a wider question once. This scan is
# that question made standing, so the next one is found by a meter rather than
# by luck.
#
# That is `REDS %102`'s family at ladder scale: a reading that sees a subset
# answers in the voice of the whole. A GREEN over part of a subject is more
# dangerous than a RED, since it answers the question nobody asked in the voice
# of the question they did. The answer is never a fourth named window; it is one
# window with no name in it at all.
#
# WHAT IT READS. Every top-level body in every rung module -- `fn` or `pub fn`
# at column zero, closing on the first bare `}` there, which is the same shape
# all three elder meters read a body by, so the four agree on what a body is.
# Bodies are compared by their exact text, so two bodies are one only when they
# stand byte for byte alike. No hashing, hence no collision to argue about.
#
# WHAT IT REPORTS.
#
#   CARRY_BODIES names how many bodies stand, how many distinct texts they are,
#   how many are a copy of one already counted, and how many lines those copies
#   carry. The last number is the carry, and it is the one a design call rests
#   on (REDS %93: a tally repeated from memory drifts).
#
#   CARRY_TOP names the families carrying the most, largest first, each as
#   `name:rungs x lines = carried`. This is the fold queue, printed rather than
#   remembered, so the next fold is chosen by measurement rather than by which
#   family somebody happened to look at.
#
# CARAVAN_CARRY_CEILING (the default named below): how many carried lines the ladder may
# hold. The scan prints what stands today rather than reciting it here, since a
# number written into a comment drifts the moment a fold lands (REDS %110). That number is far larger than any the three named meters report, and
# naming it plainly is the whole point of this scan -- the ladder's real carry
# was never the few thousand lines inside two prefixes. Each fold hands back the
# room it wins by lowering this ceiling: 143,000 came down to 137,300 when
# `mend_the_plan` lifted out of thirty-seven rungs, to 135,000 when
# `reckon_the_plan` lifted out of the same thirty-seven, to 132,700 when
# `fill_table` lifted out of forty-three, to 131,200 when `confer_slot` lifted
# out of the same forty-three at no widening cost at all, to 129,600 when
# `confer_one` lifted out of forty, to 127,600 when `weigh_the_term` lifted
# out of thirty-one, to 126,000 when `record_the_dispute` lifted out of
# thirty-three, and to 124,700 when `graft_promised_reach` lifted out of
# forty-two -- and downward on every fold since. The chain stops naming
# figures here on purpose: a list of past ceilings written into a comment
# drifts the moment a fold lands (REDS %110), and the ceiling standing
# today is the default named below, beside the carry the scan prints.
#
# A FOLD PAYS ITS SUCCESSORS. `confer_slot` needed five symbols public across
# forty-three rungs and found all five already public, because the fold before
# it had widened exactly those five for `fill_table`. So the honest price of a
# fold is charged once and spent several times, and a lap that reads only the
# widening count of the fold in front of it reads that price too high.
#
# AN ABSENTEE IS A READING TOO. `confer_one` printed here as forty rungs and
# hashing every body agreed exactly -- yet five more rungs write a body by that
# name, and all five differ in one place only: how deep they reach into the
# report. Read in ladder order they climb a staircase, one `inner` per rung,
# until the ladder learns to name the reach through an accessor and the depth
# stops being a per-rung fact. So the rungs a family leaves out say when the
# shape it shares was born, and that is worth reading before folding.
#
# AN ABSENTEE CAN ALSO BE INVITED. `weigh_the_term` printed here as thirty rungs,
# and hashing every body by that name found a thirty-first -- `lapse.rye`, which
# differs in six places that are all one difference: it OWNS the lapsing tier, so
# it reaches its own report directly where every rung above reaches it through
# `lapsing_of`. A rung that owns a tier can name the reach anyway, and a
# three-line identity accessor folded all sixty-nine of its lines with the other
# thirty. Fold M learned this on `recant.rye` and fold J on the staircase; the
# reading to make is which kind of absentee stands before you -- one dated by a
# shape born later, or one a single accessor brings home.
#
# AN ABSENTEE SET CAN BE A FOSSIL RECORD WHOLE. `provision_notes` printed here as
# twenty-four rungs at ninety-one lines, and hashing every body by that name found
# forty-seven -- twenty-three elders standing at THIRTEEN distinct shallower
# depths, from fourteen lines to eighty-six. Every one is a strict truncation of
# the canonical, so the staircase reads as the ladder's own memory of which note
# it had learned to provision on which lap. None can be brought home: no accessor
# gives a body back a check it never had. The reading to make of a large absentee
# set is therefore its SHAPE -- one depth means one shape born later, thirteen
# depths mean thirteen laps of growth, and both stay home for the same reason.
#
# AN ABSENTEE CAN STAND BELOW THE FOLD LINE. `slot_from_argv` stood byte for
# byte in FIFTY-NINE rungs, sixteen more than the body that reaches it -- and
# those sixteen are the rungs the harness itself imports. Folding them would
# have a rung the harness reaches for reach back through the harness, which
# inverts the ladder rather than lifting it. So the fold line is not the widest
# family; it is the widest family standing ABOVE the harness. This is the third
# kind of absentee the arc has met: one dated by a shape born later, one a
# single accessor brings home, and one that stays home because of where it
# stands in the import order.
#
# A FOLD QUEUE IS A LEAD, NEVER A VERDICT. This scan names families by exact
# text, so `fill_table` printed here as thirty-seven rungs carrying 2,484 lines
# while forty-three rungs actually held it -- the six it left out differ by the
# word `pub` and nothing else, one line of a sixty-nine-line body. Reading past
# the queue's own answer is what found the largest family the arc has folded.
#
# CARAVAN_CARRY_TOP (default 12): how many carrying families to name.
#
# CARAVAN_LADDER_DIR (default caravan): the directory of rung modules, so the
# PASS and FAIL fixtures prove both paths without touching the tree.
set -eu

CEILING=${CARAVAN_CARRY_CEILING:-78271}
TOP=${CARAVAN_CARRY_TOP:-12}
DIR=${CARAVAN_LADDER_DIR:-caravan}

modules=0
for f in "$DIR"/*.rye; do
  test -f "$f" || continue
  modules=$((modules + 1))
done

if [ "$modules" -eq 0 ]; then
  echo "CARRY_BAD no rung modules found under ${DIR}"
  echo "CARRY_FAIL reason=no_modules dir=${DIR}"
  exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT INT TERM

# One pass over every module. A body is keyed by its own exact text, so the
# count is a count rather than an estimate, and the family's name is kept from
# the first rung that wrote it so the report reads in words.
awk '
  FNR == 1 { inb = 0 }
  $0 ~ /^(pub )?fn [a-z_][a-z0-9_]*\(/ {
    name = ($1 == "pub") ? $3 : $2
    sub(/\(.*/, "", name); inb = 1; body = ""; n = 0
  }
  inb { body = body $0 "\n"; n++ }
  inb && /^}$/ {
    seen[body]++
    lines[body] = n
    if (seen[body] == 1) family[body] = name
    inb = 0
  }
  END {
    for (b in seen) {
      bodies += seen[b]
      distinct++
      if (seen[b] > 1) {
        copies += seen[b] - 1
        carried += (seen[b] - 1) * lines[b]
        printf "%d %d %d %s\n", (seen[b] - 1) * lines[b], seen[b], lines[b], family[b] > "'"$work"'/families"
      }
    }
    printf "%d %d %d %d\n", bodies + 0, distinct + 0, copies + 0, carried + 0
  }
' "$DIR"/*.rye > "$work/summary"

bodies=$(cut -d' ' -f1 "$work/summary")
distinct=$(cut -d' ' -f2 "$work/summary")
copies=$(cut -d' ' -f3 "$work/summary")
carried=$(cut -d' ' -f4 "$work/summary")

if [ "$bodies" -eq 0 ]; then
  echo "CARRY_BAD ${modules} modules hold no top-level bodies at all"
  echo "CARRY_FAIL reason=no_bodies dir=${DIR} modules=${modules}"
  exit 1
fi

echo "CARRY_MODULES ${modules} dir=${DIR}"

# THE SECOND READING, added `20260821.175633`. Carry counts LINES, and a three-line delegate that
# forwards to a two-hundred-line body reports as three. So carry alone can be satisfied by MOVING
# lines rather than removing them, and a meter that can be satisfied by relocation will eventually
# be satisfied that way. Delegates are the thing carry cannot see, so they are counted beside it:
# when carry falls and delegates rise by the same shape, a fold traded a cost for a cheaper-looking
# one; when carry falls and delegates hold, lines genuinely left the tree. Two readings, so no
# single number can dress movement as progress.
delegates=$(grep -rhc "return ladder_checks\." "${DIR}"/*.rye 2>/dev/null | awk '{n += $1} END {print n + 0}')
delegate_files=$(grep -rl "return ladder_checks\." "${DIR}"/*.rye 2>/dev/null | wc -l | tr -d ' ')
echo "CARRY_DELEGATES ${delegates} in_files=${delegate_files} note=lines_carry_cannot_see"
echo "CARRY_BODIES ${bodies} distinct=${distinct} copies=${copies} carried_lines=${carried}"

if [ -f "$work/families" ]; then
  families=$(wc -l < "$work/families" | tr -d ' ')
  echo "CARRY_FAMILIES ${families} carrying=1_or_more_copies"
  sort -rn "$work/families" | head -n "$TOP" | while read -r carry count len name; do
    echo "CARRY_TOP ${name}: ${count} rungs x ${len} lines = ${carry} carried"
  done
else
  echo "CARRY_FAMILIES 0 carrying=1_or_more_copies"
fi

if [ "$carried" -gt "$CEILING" ]; then
  echo "CARRY_BAD carried=${carried} stands past ceiling=${CEILING}"
  echo "CARRY_FAIL reason=past_ceiling carried=${carried} ceiling=${CEILING}"
  exit 1
fi

echo "CARRY_OK carried=${carried} ceiling=${CEILING} modules=${modules} bodies=${bodies}"
